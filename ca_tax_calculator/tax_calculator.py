from abc import ABC, abstractmethod
from typing import List, Tuple, Dict, Any


class TaxCalculator(ABC):
    """
    Abstract base class defining the shared calculation engine for Canadian
    Federal and Provincial/Territorial income tax computations.
    """

    def __init__(self, brackets: List[Tuple[float, float]], lowest_rate: float) -> None:
        self._brackets: List[Tuple[float, float]] = brackets
        self._lowest_rate: float = lowest_rate

    def calculate_gross_bracket_tax(self, taxable_income: float) -> float:
        """
        Computes gross progressive tax across marginal income brackets
        before applying non-refundable tax credits, surtaxes, or abatements.
        """
        if taxable_income <= 0:
            return 0.0

        gross_tax: float = 0.0
        previous_limit: float = 0.0

        for upper_limit, rate in self._brackets:
            if taxable_income > previous_limit:
                taxable_slice = min(taxable_income, upper_limit) - previous_limit
                gross_tax += taxable_slice * rate
                previous_limit = upper_limit
            else:
                break

        return round(gross_tax, 2)

    def get_marginal_rate(self, taxable_income: float) -> float:
        """Returns the marginal tax rate (as a decimal) for the user's top dollar."""
        if taxable_income <= 0:
            return self._brackets[0][1]

        for upper_limit, rate in self._brackets:
            if taxable_income <= upper_limit:
                return rate

        return self._brackets[-1][1]

    @staticmethod
    def calculate_claimable_medical_expenses(
        medical_expenses: float, net_income: float, max_threshold: float = 2834.00
    ) -> float:
        """
        Computes allowable medical expenses exceeding the lesser of
        3% of net income or the indexed maximum threshold ($2,834 for 2026 Federal).
        """
        if medical_expenses <= 0:
            return 0.0
        threshold = min(net_income * 0.03, max_threshold)
        return round(max(0.0, medical_expenses - threshold), 2)

    @abstractmethod
    def calculate_tax(self, tax_profile: Dict[str, Any]) -> Dict[str, float]:
        """
        Accepts the structured tax profile dictionary generated by User
        and returns a detailed dictionary of tax breakdown figures.
        """
        pass
